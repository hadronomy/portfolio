// Builds src/address-data.ts from Google's Address Data Service, the metadata
// behind libaddressinput and Chrome's address autofill. Run it again to pick
// up upstream changes:
//
//   node packages/invoices/scripts/address-data.mjs
//
// Only the top level of each country is kept: the format, which fields are
// required, the postal code pattern, the words for each field, and the first
// level of subdivisions with the postal prefixes that belong to them.
import { writeFile } from 'node:fs/promises';

const base = 'https://chromium-i18n.appspot.com/ssl-address/data';
const output = new URL('../src/address-data.ts', import.meta.url);

async function fetchJson(path) {
  for (let attempt = 1; ; attempt += 1) {
    try {
      const response = await fetch(path ? `${base}/${path}` : base, {
        signal: AbortSignal.timeout(20_000),
      });
      if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
      return await response.json();
    } catch (error) {
      if (attempt === 4) throw error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 1000));
    }
  }
}

const split = (value) => (value ? value.split('~') : []);

// Google keeps the Castilian forms of Spanish provinces whose official names
// changed. Invoices print the official name; the old one stays as the second
// name, so searching for either still finds the province.
const official = {
  ES: {
    Álava: 'Araba/Álava',
    Guipúzcoa: 'Gipuzkoa',
    'Islas Baleares': 'Illes Balears',
    'La Coruña': 'A Coruña',
    Lérida: 'Lleida',
    Vizcaya: 'Bizkaia',
  },
};

// Formats that differ from how the country's post asks for addresses. Correos
// puts the province on its own line, under the postal code and locality;
// Google runs all three together, which reads as one long place name.
const formats = {
  ES: '%A%n%Z %C%n%S',
};

const defaults = await fetchJson('ZZ');
const { countries } = await fetchJson('');
const codes = split(countries);

const entries = [];
for (const code of codes) {
  const raw = { ...defaults, ...(await fetchJson(code)) };
  // The Latin-script format where there is one: invoices here are written
  // in English or Spanish, so a Japanese address reads street first.
  const fmt = (formats[code] ?? raw.lfmt ?? raw.fmt).replace(
    /%[NO]%n|%n%[NO]|%[NO]/g,
    '',
  );
  const keys = split(raw.sub_keys);
  const names = split(raw.sub_names);
  const latin = split(raw.sub_lnames);
  const zips = split(raw.sub_zips);
  const regions = keys.map((key, index) => {
    // With Latin names present, the keys are the names in the local script.
    const given = latin[index] || names[index] || key;
    const local = latin.length ? names[index] || key : '';
    const name = official[code]?.[given] ?? given;
    const other = name !== given ? given : local !== name ? local : '';
    return [name, other, zips[index] ?? ''];
  });
  entries.push({
    code,
    fmt,
    require: raw.require.replace(/[NO]/g, ''),
    zip: raw.zip ?? '',
    zipex: split(raw.zipex?.replace(/,/g, '~'))[0] ?? '',
    zipName: raw.zip_name_type,
    regionName: raw.state_name_type,
    localityName: raw.locality_name_type,
    sublocalityName: raw.sublocality_name_type,
    regions,
  });
  process.stdout.write(`${code} `);
}

const trim = (regions) =>
  regions.map((region) => {
    const [name, local, zip] = region;
    return zip ? [name, local, zip] : local ? [name, local] : [name];
  });

const body = entries
  .map(
    ({ code, regions, ...entry }) =>
      `  ${code}: ${JSON.stringify({ ...entry, regions: trim(regions) })},`,
  )
  .join('\n');

await writeFile(
  output,
  `// Generated by scripts/address-data.mjs from Google's Address Data Service
// (https://chromium-i18n.appspot.com/ssl-address). Do not edit by hand.
//
// fmt uses libaddressinput's tokens: %A street lines, %D dependent locality,
// %C locality, %S region, %Z postal code, %X sorting code, %n a line break.
// A region is [name, local name, postal prefix pattern], with the last two
// left out when empty.

export const addressData = {
${body}
} as const;
`,
);
console.log(`\nwrote ${entries.length} countries`);
