/** A calendar day as a document prints it: 9 Nov 2026, 9 nov 2026. */
export const formatDay = (day: string, language: Language) =>
  new Intl.DateTimeFormat(language === 'es' ? 'es-ES' : 'en-US', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${day}T12:00:00Z`));
